export type HallucinationReason =
  | "invented_date"
  | "invented_balance"
  | "invented_account_detail"
  | "unknown_citation";

export interface GroundedLetterContext {
  allowedFacts: {
    creditorName: string;
    accountNumber: string;
    balance: string | "unconfirmed";
    dateOfFirstDelinquency: string | "not provided by bureau";
    reportingBureaus: string[];
    accountStatus: string;
    itemType: string;
    accountTail: string;
  };
  unconfirmedFields: string[];
  groundingDirective: string;
}

export interface GroundingValidationResult {
  passed: boolean;
  suspectedHallucinations: Array<{
    text: string;
    reason: HallucinationReason;
    severity: "BLOCK" | "WARN";
  }>;
}

